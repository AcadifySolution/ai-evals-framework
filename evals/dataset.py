import json
from typing import List, Dict, Any, Union, Optional
import pandas as pd
from pydantic import BaseModel, Field


class EvaluationSample(BaseModel):
    """Schema representing a single evaluation unit."""
    query: str = Field(..., description="The input query/prompt sent to the model under test")
    context: Union[str, List[str]] = Field(
        default="", 
        description="The source documents or context retrieved for RAG, used to check for hallucinations"
    )
    ground_truth: Optional[str] = Field(
        default=None, 
        description="The gold standard expected response to measure correctness against"
    )
    generated_output: str = Field(
        ..., 
        description="The response generated by the LLM system under test"
    )
    metadata: Dict[str, Any] = Field(
        default_factory=dict, 
        description="Arbitrary execution metadata (e.g. latency, token count, cost, trace_id)"
    )

    @property
    def contexts_as_list(self) -> List[str]:
        """Ensures context is returned consistently as a list of strings."""
        if isinstance(self.context, list):
            return self.context
        return [self.context] if self.context else []

    @property
    def context_as_str(self) -> str:
        """Ensures context is returned consistently as a combined string."""
        if isinstance(self.context, list):
            return "\n".join(self.context)
        return self.context


class GroundTruthDataset:
    """Manages collection of evaluation samples with validation logic."""
    def __init__(self, samples: List[EvaluationSample] = None):
        self.samples: List[EvaluationSample] = samples or []

    def add_sample(self, sample: EvaluationSample):
        """Adds a verified evaluation sample to the dataset."""
        self.samples.append(sample)

    @classmethod
    def load_from_json(cls, filepath: str) -> "GroundTruthDataset":
        """Loads and validates evaluation samples from a JSON file."""
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)
        
        # Expect either a list of dicts, or a dictionary containing a 'samples' key
        raw_samples = data if isinstance(data, list) else data.get("samples", [])
        validated_samples = [EvaluationSample(**s) for s in raw_samples]
        return cls(validated_samples)

    @classmethod
    def load_from_jsonl(cls, filepath: str) -> "GroundTruthDataset":
        """Loads and validates evaluation samples from a JSON Lines (.jsonl) file."""
        samples = []
        with open(filepath, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    samples.append(EvaluationSample(**json.loads(line)))
        return cls(samples)

    @classmethod
    def load_from_csv(cls, filepath: str) -> "GroundTruthDataset":
        """Loads and validates evaluation samples from a CSV file."""
        df = pd.read_csv(filepath)
        return cls.load_from_dataframe(df)

    @classmethod
    def load_from_dataframe(cls, df: pd.DataFrame) -> "GroundTruthDataset":
        """Converts and validates a Pandas DataFrame into evaluation samples."""
        samples = []
        for _, row in df.iterrows():
            # Handle list parsing from csv if saved as strings
            context_val = row.get("context", "")
            if isinstance(context_val, str) and context_val.startswith("[") and context_val.endswith("]"):
                try:
                    context_val = json.loads(context_val)
                except Exception:
                    pass
            
            metadata_val = row.get("metadata", {})
            if isinstance(metadata_val, str):
                try:
                    metadata_val = json.loads(metadata_val)
                except Exception:
                    metadata_val = {}

            samples.append(
                EvaluationSample(
                    query=str(row["query"]),
                    context=context_val,
                    ground_truth=str(row["ground_truth"]) if pd.notna(row.get("ground_truth")) else None,
                    generated_output=str(row["generated_output"]),
                    metadata=metadata_val
                )
            )
        return cls(samples)

    def to_dataframe(self) -> pd.DataFrame:
        """Converts dataset samples back to a Pandas DataFrame."""
        return pd.DataFrame([s.model_dump() for s in self.samples])
